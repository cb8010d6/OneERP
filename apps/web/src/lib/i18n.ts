const dictionaries = {
  'zh-CN': zh,
  'en-US': en,
};

function normalizeLanguage(language: unknown): Language {
  return language === 'en-US' ? 'en-US' : 'zh-CN';
}

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'zh-CN';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return normalizeLanguage(stored);
}

interface I18nState {
  language: Language;
  setLanguage: (language: Language | string) => void;
  hydrateLanguage: () => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  language: 'zh-CN',
  setLanguage: (nextLanguage) => {
    const language = normalizeLanguage(nextLanguage);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, language);
      window.document.documentElement.lang = language;
    }
    set({ language });
  },
  hydrateLanguage: () => {
    const language = getInitialLanguage();
    window.document.documentElement.lang = language;
    set({ language });
  },
}));

export type TranslationKey = keyof typeof zh;

export function translate(language: Language | string | undefined, key: TranslationKey) {
  const dictionary = dictionaries[normalizeLanguage(language)];
  return dictionary[key] ?? dictionaries['zh-CN'][key] ?? key;
}

export function useI18n() {
  const language = useI18nStore((state) => state.language);
  const setLanguage = useI18nStore((state) => state.setLanguage);

  return {
    language,
    setLanguage,
    t: (key: TranslationKey) => translate(language, key),
    locale: language,
  };
}
